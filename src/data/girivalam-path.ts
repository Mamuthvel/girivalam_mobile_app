// Total Girivalam path distance (approximately 14 km)
export const TOTAL_GIRIVALAM_DISTANCE = 14.0; // km

// Geo-fence buffer zone around the path (in meters)
export const GEOFENCE_BUFFER_METERS = 75; // 75 meters buffer zone

// Calculate if a point is within the geo-fence
export function isWithinGeofence(
  userLat: number,
  userLng: number,
  bufferMeters: number = GEOFENCE_BUFFER_METERS
): { withinFence: boolean; closestPoint: PathPoint | null; distanceToPath: number } {
  let minDistance = Infinity;
  let closestPoint: PathPoint | null = null;

  for (const point of girivalamPath) {
    const distance = calculateDistance(userLat, userLng, point.lat, point.lng) * 1000; // convert to meters
    if (distance < minDistance) {
      minDistance = distance;
      closestPoint = point;
    }
  }

  return {
    withinFence: minDistance <= bufferMeters,
    closestPoint,
    distanceToPath: minDistance
  };
}

// Calculate distance between two points using Haversine formula
function calculateDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
    Math.cos((lat2 * Math.PI) / 180) *
    Math.sin(dLon / 2) *
    Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find the closest point on path and calculate progress
export function calculatePathProgress(
  userLat: number,
  userLng: number
): { completionPercentage: number; distanceCovered: number; closestPoint: PathPoint | null } {
  const { closestPoint } = isWithinGeofence(userLat, userLng);

  if (!closestPoint) {
    return { completionPercentage: 0, distanceCovered: 0, closestPoint: null };
  }

  const distanceCovered = closestPoint.distance || 0;
  const completionPercentage = (distanceCovered / TOTAL_GIRIVALAM_DISTANCE) * 100;

  return {
    completionPercentage: Math.min(completionPercentage, 100),
    distanceCovered,
    closestPoint
  };
}
